
public class RecipeData
{
    public string Result;
    public string Ing1;
    public string Ing2;
    public string Ing3;

    public RecipeData(string result, string ing1, string ing2, string ing3)
    {
        Result = result;
        Ing1 = ing1;
        Ing2 = ing2;
        Ing3 = ing3;
    }
}